#!/usr/bin/env bash
# ==============================================================================
# 민성이의 가계부 - Self-hosted Appwrite 자동 설치 및 설정 도구
# ==============================================================================

set -e

echo "======================================================================"
echo " 📦 [1/2] Appwrite 데이터 디렉터리 준비"
echo "======================================================================"

mkdir -p appwrite
cd appwrite

echo "======================================================================"
echo " 🐳 [2/2] Appwrite 컨테이너 스택 설치"
echo "   - 주의: 리버스 프록시(NPM)가 80/443 포트를 사용하므로,"
echo "     Appwrite HTTP 포트는 8080으로 권장 배정합니다."
echo "======================================================================"

docker run -i --rm \
    --volume /var/run/docker.sock:/var/run/docker.sock \
    --volume "$(pwd)":/usr/src/code/appwrite:rw \
    --entrypoint="install" \
    appwrite/appwrite:1.6.0

echo "✅ Appwrite 설치가 완료되었습니다."
echo "   - 브라우저에서 http://[서버IP]:8080 또는 NPM 프록시 도메인으로 접속하여"
echo "   - 초기 관리자 계정을 생성하고 새 Project(예: ledger-project)를 만드세요."
